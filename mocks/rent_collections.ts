/** Rent growth from October to November per contract, so each contract shows its own trend. */
const growth: Record<string, number> = {
  "CG-2026-0001": 1.05,
  "CG-2026-0002": 1.12,
  "CG-2026-0003": 1.03,
  "CG-2026-0005": 1.1,
  "CG-2026-0007": 0.96,
};

/** October's rent per contract, derived from November's payments received. */
const previousMonthRents = Object.entries(growth).map(([management, factor]) => {
  const november = collections
    .filter((collection) => collection.management.reference === management && isReceived(collection))
    .reduce((sum, collection) => sum + linesTotal(collection, "loyer"), 0);
  return { management, amount: Math.round(november / factor / 1000) * 1000 };
});

